const rows = lessons.flatMap((lesson) =>
  lesson.tokens.map((token, tokenIndex) => {
    const row = {
      ...Object.fromEntries(COURSE_CSV_HEADERS.map((header) => [header, ""])),
      ...shared,
      sentence_id: lesson.sentenceId,
      sentence_order: String(lesson.sentenceOrder),
      sentence_pattern_id: lesson.patternId,
      pattern_name: lesson.patternName,
      pattern_cefr: "A2",
      is_new_sentence_pattern: "TRUE",
      lesson_id: lesson.lessonId,
      lesson_title: lesson.title,
      sentence: lesson.sentence,
      translation: lesson.translation,
      grammar: lesson.grammar,
      occurrence_id: `${lesson.sentenceId}-t${String(tokenIndex + 1).padStart(2, "0")}`,
      token_order: String(tokenIndex + 1),
      partOfSpeech: token.context_pos,
      is_new_pattern: tokenIndex === 0 ? "TRUE" : "FALSE",
      is_new_combination: token.chunk_id ? "TRUE" : "FALSE",
      is_new_content:
        token.is_new_word === "TRUE" ||
        ["watched", "went", "going"].includes(token.answer)
          ? "TRUE"
          : "FALSE",
      ...token,
    };
    return Object.fromEntries(
      COURSE_CSV_HEADERS.map((header) => [header, row[header] ?? ""]),
    );
  }),
);

fs.writeFileSync(
  path.join(root, "public/data/a2-course-v1.csv"),
  `${serializeCourseCsv(rows)}\r\n`,
  "utf8",
);
console.log(
  `Created public/data/a2-course-v1.csv with ${rows.length} occurrences.`,
);
