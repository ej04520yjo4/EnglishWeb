const knownToken = (answer, lexemeId) => {
  const row = a1Rows.find(
    (candidate) =>
      candidate.answer.toLowerCase() === answer.toLowerCase() &&
      candidate.lexeme_id === lexemeId,
  );
  if (!row) {
    throw new Error(`A1 找不到可沿用的詞彙：${answer}/${lexemeId}`);
  }
  return {
    token_id: row.token_id,
    lexeme_id: row.lexeme_id,
    lemma: row.lemma,
    dictionary_pos: row.dictionary_pos,
    kk_us: row.kk_us,
    ipa_us: row.ipa_us,
    ipa_standalone: row.ipa_standalone,
    kk: row.kk,
    ipa: row.ipa,
    syllables: row.syllables,
    stress_syllable: row.stress_syllable,
    display_syllables: row.display_syllables,
    is_new_word: "FALSE",
  };
};

